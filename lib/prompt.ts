export function escapeXml(value: string) {
  return value.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;').replaceAll("'", '&apos;');
}
export function buildContents(faq: string, question: string) {
  return `<faq>\n${escapeXml(faq)}\n</faq>\n<question>\n${escapeXml(question)}\n</question>`;
}
